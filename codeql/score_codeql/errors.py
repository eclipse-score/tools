"""Exception types shared by all modules."""

from __future__ import annotations


class ScaError(Exception):
    """A fatal, user-facing error. ``exit_code`` becomes the process exit status."""

    def __init__(self, message: str, exit_code: int = 1) -> None:
        super().__init__(message)
        self.exit_code = exit_code


class ConfigError(ScaError):
    """Invalid or inconsistent report/pack configuration."""
